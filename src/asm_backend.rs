use crate::ast::*;
use std::collections::HashMap;

struct AsmCtx {
    out: String,
    struct_fields: HashMap<String, Vec<String>>,
    rodata: Vec<(String, String)>,
    ptr_params: std::collections::HashSet<String>,
    locals: HashMap<String, i32>,
    consts: HashMap<String, i64>,
    stack_size: i32,
    label_id: usize,
    loop_labels: Vec<(String, String)>,
    epilogue_lbl: String,
}

impl AsmCtx {
    fn new(consts: HashMap<String, i64>) -> Self {
        Self {
            out: String::new(),
            struct_fields: HashMap::new(),
            rodata: Vec::new(),
            ptr_params: std::collections::HashSet::new(),
            locals: HashMap::new(),
            consts,
            stack_size: 0,
            label_id: 0,
            loop_labels: Vec::new(),
            epilogue_lbl: String::new(),
        }
    }

    fn intern_str(&mut self, val: &str) -> String {
        let lbl = self.next_label("str");
        self.rodata.push((lbl.clone(), val.to_string()));
        lbl
    }

    fn next_label(&mut self, prefix: &str) -> String {
        self.label_id += 1;
        format!(".L_{}_{}", prefix, self.label_id)
    }

    fn alloc_local(&mut self, name: &str, bytes: i32) -> i32 {
        self.stack_size += bytes;
        let off = -self.stack_size;
        self.locals.insert(name.to_string(), off);
        off
    }

    fn emit(&mut self, line: &str) {
        self.out.push_str("    ");
        self.out.push_str(line);
        self.out.push('\n');
    }

    fn emit_raw(&mut self, line: &str) {
        self.out.push_str(line);
        self.out.push('\n');
    }
}

fn peephole_optimize_asm(asm: &str) -> String {
    let lines: Vec<&str> = asm.lines().collect();
    let mut out: Vec<String> = Vec::with_capacity(lines.len());
    let mut i = 0;
    while i < lines.len() {
        let cur = lines[i].trim();
        if cur == "addl $0, %eax" || cur == "subl $0, %eax" {
            i += 1;
            continue;
        }
        if i + 1 < lines.len() {
            let nxt = lines[i + 1].trim();

            if cur == "pushl %eax" && nxt == "popl %eax" {
                i += 2;
                continue;
            }

            if let (Some(dst), Some(src)) = (
                cur.strip_prefix("movl %eax, "),
                nxt.strip_prefix("movl ")
                    .and_then(|r| r.strip_suffix(", %eax")),
            ) {
                if dst == src {
                    out.push(lines[i].to_string());
                    i += 2;
                    continue;
                }
            }

            if let Some(lbl) = cur.strip_prefix("jmp ") {
                if nxt == format!("{}:", lbl) {
                    i += 1;
                    continue;
                }
            }
        }
        out.push(lines[i].to_string());
        i += 1;
    }
    let mut res = out.join("\n");
    res.push('\n');
    res
}

pub fn generate_x86_asm(program: &Program, is_kernel: bool) -> String {
    let mut consts = HashMap::new();
    for en in &program.enums {
        for (vname, val, _) in &en.variants {
            consts.insert(format!("{}::{}", en.name, vname), *val);
        }
    }
    for c in &program.consts {
        if let Some(v) = eval_const(&c.value, &consts) {
            consts.insert(c.name.clone(), v);
        }
    }

    let mut ctx = AsmCtx::new(consts);
    for st in &program.structs {
        ctx.struct_fields.insert(
            st.name.clone(),
            st.fields.iter().map(|f| f.name.clone()).collect(),
        );
    }
    ctx.emit_raw("# Generated by VETO Native x86 Backend (0 GCC dependency)");
    ctx.emit_raw(".code32");

    if is_kernel {
        ctx.emit_raw(".section .multiboot, \"a\"");
        ctx.emit_raw(".align 4");
        ctx.emit_raw(".long 0x1BADB002");
        ctx.emit_raw(".long 0x00000000");
        ctx.emit_raw(".long 0xE4524FFE");
        ctx.emit_raw(".bss");
        ctx.emit_raw(".align 16");
        ctx.emit_raw("kernel_stack_bottom:");
        ctx.emit_raw(".skip 16384");
        ctx.emit_raw("kernel_stack_top:");
        ctx.emit_raw(".text");
        ctx.emit_raw(".global _start");
        ctx.emit_raw("_start:");
        ctx.emit("cli");
        ctx.emit("movl $kernel_stack_top, %esp");
        ctx.emit("andl $-16, %esp");
        ctx.emit("call main");
        ctx.emit("cli");
        ctx.emit_raw(".L_halt:");
        ctx.emit("hlt");
        ctx.emit("jmp .L_halt");
        ctx.emit_raw("__veto_vga_print:");
        ctx.emit("pushl %ebp");
        ctx.emit("movl %esp, %ebp");
        ctx.emit("pushl %ebx");
        ctx.emit("pushl %esi");
        ctx.emit("pushl %edi");
        ctx.emit("movl 8(%ebp), %eax");
        ctx.emit("imull $80, %eax");
        ctx.emit("addl 12(%ebp), %eax");
        ctx.emit("movl %eax, %edi");
        ctx.emit("movl 16(%ebp), %esi");
        ctx.emit("movzbl 20(%ebp), %edx");
        ctx.emit("shll $8, %edx");
        ctx.emit_raw(".L_vga_loop:");
        ctx.emit("cmpl $2000, %edi");
        ctx.emit("jge .L_vga_done");
        ctx.emit("movzbl (%esi), %eax");
        ctx.emit("testb %al, %al");
        ctx.emit("jz .L_vga_done");
        ctx.emit("orl %edx, %eax");
        ctx.emit("movw %ax, 0xB8000(,%edi,2)");
        ctx.emit("incl %esi");
        ctx.emit("incl %edi");
        ctx.emit("jmp .L_vga_loop");
        ctx.emit_raw(".L_vga_done:");
        ctx.emit("popl %edi");
        ctx.emit("popl %esi");
        ctx.emit("popl %ebx");
        ctx.emit("popl %ebp");
        ctx.emit("ret");
    } else {
        ctx.emit_raw(".text");
    }

    for func in &program.functions {
        emit_function(&mut ctx, func, program);
    }

    if !ctx.rodata.is_empty() {
        ctx.emit_raw(".section .rodata");
        let items = ctx.rodata.clone();
        for (lbl, text) in items {
            let escaped = text.replace('\\', "\\\\").replace('"', "\\\"");
            ctx.emit_raw(&format!("{}:", lbl));
            ctx.emit(&format!(r#".asciz "{}""#, escaped));
        }
    }

    peephole_optimize_asm(&ctx.out)
}

fn eval_const(expr: &Expr, consts: &HashMap<String, i64>) -> Option<i64> {
    match expr {
        Expr::Number(n) => Some(*n),
        Expr::Var(v) => consts.get(v).copied(),
        Expr::EnumVal(en, var, _) => consts.get(&format!("{}::{}", en, var)).copied(),
        Expr::BinOp(l, op, r) => {
            let a = eval_const(l, consts)?;
            let b = eval_const(r, consts)?;
            match op.as_str() {
                "+" => Some(a.wrapping_add(b)),
                "-" => Some(a.wrapping_sub(b)),
                "*" => Some(a.wrapping_mul(b)),
                "/" if b != 0 => Some(a / b),
                "%" if b != 0 => Some(a % b),
                "<<" => Some(a << b),
                ">>" => Some(a >> b),
                "&" => Some(a & b),
                "|" => Some(a | b),
                "^" => Some(a ^ b),
                _ => None,
            }
        }
        _ => None,
    }
}

fn emit_function(ctx: &mut AsmCtx, func: &Function, program: &Program) {
    ctx.locals.clear();
    ctx.ptr_params.clear();
    ctx.stack_size = 0;
    ctx.epilogue_lbl = ctx.next_label("epilogue");
    for (_i, p) in func.params.iter().enumerate() {
        if p.is_mut_ref {
            ctx.ptr_params.insert(p.name.clone());
            if let Some(fields) = ctx.struct_fields.get(&p.type_name).cloned() {
                for (fidx, fname) in fields.iter().enumerate() {
                    ctx.locals
                        .insert(format!("{}.{}", p.name, fname), (fidx as i32) * 4);
                }
            }
        }
    }

    for (i, p) in func.params.iter().enumerate() {
        let param_off = 8 + (i as i32) * 4;
        ctx.locals.insert(p.name.clone(), param_off);
    }

    reserve_locals(ctx, &func.body, program);
    let aligned_stack = (ctx.stack_size + 15) & !15;

    ctx.emit_raw(&format!(".global {}", func.name));
    ctx.emit_raw(&format!("{}:", func.name));
    if func.attrs.iter().any(|a| a == "interrupt") {
        ctx.emit("pusha");
    }
    ctx.emit("pushl %ebp");
    ctx.emit("movl %esp, %ebp");
    if aligned_stack > 0 {
        ctx.emit(&format!("subl ${}, %esp", aligned_stack));
    }

    emit_stmts(ctx, &func.body, program);

    ctx.emit_raw(&format!("{}:", ctx.epilogue_lbl.clone()));
    ctx.emit("movl %ebp, %esp");
    ctx.emit("popl %ebp");
    if func.attrs.iter().any(|a| a == "interrupt") {
        ctx.emit("popa");
        ctx.emit("iret");
    } else {
        ctx.emit("ret");
    }
    ctx.emit_raw("");
}

fn reserve_locals(ctx: &mut AsmCtx, stmts: &[Stmt], program: &Program) {
    for stmt in stmts {
        match stmt {
            Stmt::Let {
                name, type_name, ..
            } => {
                if let Some(st) = program.structs.iter().find(|s| s.name == *type_name) {
                    let base = ctx.alloc_local(name, (st.fields.len().max(1) as i32) * 4);
                    for (idx, f) in st.fields.iter().enumerate() {
                        ctx.locals
                            .insert(format!("{}.{}", name, f.name), base + (idx as i32) * 4);
                    }
                } else {
                    ctx.alloc_local(name, 4);
                }
            }
            Stmt::LetArray { name, len, .. } => {
                ctx.alloc_local(name, (*len as i32) * 4);
            }
            Stmt::For { var, body, .. } => {
                ctx.alloc_local(var, 4);
                reserve_locals(ctx, body, program);
            }
            Stmt::Loop { body, .. } | Stmt::While { body, .. } => {
                reserve_locals(ctx, body, program);
            }
            Stmt::If {
                then_body,
                else_body,
                ..
            } => {
                reserve_locals(ctx, then_body, program);
                reserve_locals(ctx, else_body, program);
            }
            Stmt::Match { arms, .. } => {
                for arm in arms {
                    if let MatchPat::EnumVal(_, _, Some(b)) = &arm.pat {
                        ctx.alloc_local(b, 4);
                    }
                    reserve_locals(ctx, &arm.body, program);
                }
            }
            _ => {}
        }
    }
}

fn emit_stmts(ctx: &mut AsmCtx, stmts: &[Stmt], program: &Program) {
    for stmt in stmts {
        match stmt {
            Stmt::Let { name, value, .. } => {
                if let Expr::StructInit(_, inits) = value {
                    for (fname, fexpr) in inits {
                        emit_expr(ctx, fexpr, program);
                        if let Some(&off) = ctx.locals.get(&format!("{}.{}", name, fname)) {
                            ctx.emit(&format!("movl %eax, {}(%ebp)", off));
                        }
                    }
                } else {
                    emit_expr(ctx, value, program);
                    if let Some(&off) = ctx.locals.get(name) {
                        ctx.emit(&format!("movl %eax, {}(%ebp)", off));
                    }
                }
            }
            Stmt::LetArray { name, elements, .. } => {
                if let Some(&base) = ctx.locals.get(name) {
                    for (idx, el) in elements.iter().enumerate() {
                        emit_expr(ctx, el, program);
                        ctx.emit(&format!("movl %eax, {}(%ebp)", base + (idx as i32) * 4));
                    }
                }
            }
            Stmt::Assign { name, value, .. } => {
                emit_expr(ctx, value, program);
                if let Some(&off) = ctx.locals.get(name) {
                    ctx.emit(&format!("movl %eax, {}(%ebp)", off));
                }
            }
            Stmt::FieldAssign {
                obj, field, value, ..
            } => {
                emit_expr(ctx, value, program);
                if ctx.ptr_params.contains(obj) {
                    if let (Some(&ptr_off), Some(&foff)) = (
                        ctx.locals.get(obj),
                        ctx.locals.get(&format!("{}.{}", obj, field)),
                    ) {
                        ctx.emit(&format!("movl {}(%ebp), %ecx", ptr_off));
                        ctx.emit(&format!("movl %eax, {}(%ecx)", foff));
                    }
                } else if let Some(&off) = ctx.locals.get(&format!("{}.{}", obj, field)) {
                    ctx.emit(&format!("movl %eax, {}(%ebp)", off));
                }
            }
            Stmt::IndexAssign {
                name, index, value, ..
            } => {
                emit_expr(ctx, value, program);
                ctx.emit("pushl %eax");
                emit_expr(ctx, index, program);
                ctx.emit("popl %ecx");
                if let Some(&base) = ctx.locals.get(name) {
                    ctx.emit(&format!("movl %ecx, {}(%ebp,%eax,4)", base));
                }
            }
            Stmt::ExprStmt { expr, .. } => {
                emit_expr(ctx, expr, program);
            }
            Stmt::If {
                cond,
                then_body,
                else_body,
                ..
            } => {
                let else_lbl = ctx.next_label("else");
                let end_lbl = ctx.next_label("endif");
                emit_expr(ctx, cond, program);
                ctx.emit("cmpl $0, %eax");
                ctx.emit(&format!("je {}", else_lbl));
                emit_stmts(ctx, then_body, program);
                ctx.emit(&format!("jmp {}", end_lbl));
                ctx.emit_raw(&format!("{}:", else_lbl));
                emit_stmts(ctx, else_body, program);
                ctx.emit_raw(&format!("{}:", end_lbl));
            }
            Stmt::Loop { body, .. } => {
                let start_lbl = ctx.next_label("loop");
                let end_lbl = ctx.next_label("endloop");
                ctx.loop_labels.push((start_lbl.clone(), end_lbl.clone()));
                ctx.emit_raw(&format!("{}:", start_lbl));
                emit_stmts(ctx, body, program);
                ctx.emit(&format!("jmp {}", start_lbl));
                ctx.emit_raw(&format!("{}:", end_lbl));
                ctx.loop_labels.pop();
            }
            Stmt::While { cond, body, .. } => {
                let start_lbl = ctx.next_label("while");
                let end_lbl = ctx.next_label("endwhile");
                ctx.loop_labels.push((start_lbl.clone(), end_lbl.clone()));
                ctx.emit_raw(&format!("{}:", start_lbl));
                emit_expr(ctx, cond, program);
                ctx.emit("cmpl $0, %eax");
                ctx.emit(&format!("je {}", end_lbl));
                emit_stmts(ctx, body, program);
                ctx.emit(&format!("jmp {}", start_lbl));
                ctx.emit_raw(&format!("{}:", end_lbl));
                ctx.loop_labels.pop();
            }
            Stmt::For {
                var,
                start,
                end,
                body,
                ..
            } => {
                let cond_lbl = ctx.next_label("for_cond");
                let step_lbl = ctx.next_label("for_step");
                let end_lbl = ctx.next_label("for_end");
                let off = *ctx.locals.get(var).unwrap_or(&-4);
                emit_expr(ctx, start, program);
                ctx.emit(&format!("movl %eax, {}(%ebp)", off));
                ctx.loop_labels.push((step_lbl.clone(), end_lbl.clone()));
                ctx.emit_raw(&format!("{}:", cond_lbl));
                emit_expr(ctx, end, program);
                ctx.emit(&format!("cmpl %eax, {}(%ebp)", off));
                ctx.emit(&format!("jge {}", end_lbl));
                emit_stmts(ctx, body, program);
                ctx.emit_raw(&format!("{}:", step_lbl));
                ctx.emit(&format!("incl {}(%ebp)", off));
                ctx.emit(&format!("jmp {}", cond_lbl));
                ctx.emit_raw(&format!("{}:", end_lbl));
                ctx.loop_labels.pop();
            }
            Stmt::Match { expr, arms, .. } => {
                let end_lbl = ctx.next_label("endmatch");
                emit_expr(ctx, expr, program);
                ctx.emit("pushl %eax");
                for arm in arms {
                    let next_arm = ctx.next_label("arm_next");
                    match &arm.pat {
                        MatchPat::Wildcard => {}
                        MatchPat::Num(n) => {
                            ctx.emit(&format!("cmpl ${}, (%esp)", n));
                            ctx.emit(&format!("jne {}", next_arm));
                        }
                        MatchPat::Range(lo, hi) => {
                            ctx.emit(&format!("cmpl ${}, (%esp)", lo));
                            ctx.emit(&format!("jl {}", next_arm));
                            ctx.emit(&format!("cmpl ${}, (%esp)", hi));
                            ctx.emit(&format!("jg {}", next_arm));
                        }
                        MatchPat::EnumVal(en, var, bind) => {
                            if let Some(b) = bind {
                                let off = *ctx.locals.get(b).unwrap_or(&-4);
                                ctx.emit(&format!("movl %edx, {}(%ebp)", off));
                            }
                            let val = ctx
                                .consts
                                .get(&format!("{}::{}", en, var))
                                .copied()
                                .unwrap_or(0);
                            ctx.emit(&format!("cmpl ${}, (%esp)", val));
                            ctx.emit(&format!("jne {}", next_arm));
                        }
                    }
                    emit_stmts(ctx, &arm.body, program);
                    ctx.emit(&format!("jmp {}", end_lbl));
                    ctx.emit_raw(&format!("{}:", next_arm));
                }
                ctx.emit_raw(&format!("{}:", end_lbl));
                ctx.emit("addl $4, %esp");
            }
            Stmt::Break { .. } => {
                if let Some((_, brk)) = ctx.loop_labels.last().cloned() {
                    ctx.emit(&format!("jmp {}", brk));
                }
            }
            Stmt::Continue { .. } => {
                if let Some((cnt, _)) = ctx.loop_labels.last().cloned() {
                    ctx.emit(&format!("jmp {}", cnt));
                }
            }
            Stmt::Prove { .. } => {}
            Stmt::InlineAsm { template, .. } => {
                ctx.emit(template);
            }
            Stmt::Return { expr, .. } => {
                emit_expr(ctx, expr, program);
                ctx.emit(&format!("jmp {}", ctx.epilogue_lbl.clone()));
            }
        }
    }
}
fn emit_expr(ctx: &mut AsmCtx, expr: &Expr, program: &Program) {
    match expr {
        Expr::Number(n) => ctx.emit(&format!("movl ${}, %eax", n)),
        Expr::Str(text) => {
            let lbl = ctx.intern_str(text);
            ctx.emit(&format!("movl ${}, %eax", lbl));
        }
        Expr::EnumVal(en, var, payload) => {
            if let Some(pexpr) = payload {
                emit_expr(ctx, pexpr, program);
                ctx.emit("movl %eax, %edx");
            } else {
                ctx.emit("xorl %edx, %edx");
            }
            let v = ctx
                .consts
                .get(&format!("{}::{}", en, var))
                .copied()
                .unwrap_or(0);
            ctx.emit(&format!("movl ${}, %eax", v));
        }
        Expr::Var(name) => {
            if let Some(&c) = ctx.consts.get(name) {
                ctx.emit(&format!("movl ${}, %eax", c));
            } else if let Some(&off) = ctx.locals.get(name) {
                if off < 0 {
                    ctx.emit(&format!("movl {}(%ebp), %eax", off));
                } else {
                    ctx.emit(&format!("movl {}(%ebp), %eax", off));
                }
            } else {
                ctx.emit("movl $0, %eax");
            }
        }
        Expr::Field(obj, field) => {
            if ctx.ptr_params.contains(obj) {
                if let (Some(&ptr_off), Some(&foff)) = (
                    ctx.locals.get(obj),
                    ctx.locals.get(&format!("{}.{}", obj, field)),
                ) {
                    ctx.emit(&format!("movl {}(%ebp), %ecx", ptr_off));
                    ctx.emit(&format!("movl {}(%ecx), %eax", foff));
                } else {
                    ctx.emit("movl $0, %eax");
                }
            } else if let Some(&off) = ctx.locals.get(&format!("{}.{}", obj, field)) {
                ctx.emit(&format!("movl {}(%ebp), %eax", off));
            } else {
                ctx.emit("movl $0, %eax");
            }
        }
        Expr::Index(arr, idx) => {
            emit_expr(ctx, idx, program);
            if let Some(&base) = ctx.locals.get(arr) {
                if base < 0 {
                    ctx.emit(&format!("movl {}(%ebp,%eax,4), %eax", base));
                } else {
                    ctx.emit(&format!("movl {}(%ebp), %ecx", base));
                    ctx.emit("movl (%ecx,%eax,4), %eax");
                }
            }
        }
        Expr::UnaryNot(inner) => {
            emit_expr(ctx, inner, program);
            ctx.emit("cmpl $0, %eax");
            ctx.emit("sete %al");
            ctx.emit("movzbl %al, %eax");
        }
        Expr::MethodCall(obj, method, args) => {
            let mangled = program
                .functions
                .iter()
                .find(|f| f.name.ends_with(&format!("__{}", method)))
                .map(|f| f.name.clone())
                .unwrap_or_else(|| method.clone());
            let mut full_args = vec![Expr::Var(obj.clone())];
            full_args.extend(args.iter().cloned());
            emit_expr(ctx, &Expr::Call(mangled, full_args), program);
        }
        Expr::Call(name, args) => {
            match name.as_str() {
                "vga_print" if args.len() == 4 => {
                    for arg in args.iter().rev() {
                        emit_expr(ctx, arg, program);
                        ctx.emit("pushl %eax");
                    }
                    ctx.emit("call __veto_vga_print");
                    ctx.emit("addl $16, %esp");
                    return;
                }
                "vga_poke" if args.len() == 3 => {
                    emit_expr(ctx, &args[0], program);
                    ctx.emit("pushl %eax");
                    emit_expr(ctx, &args[1], program);
                    ctx.emit("pushl %eax");
                    emit_expr(ctx, &args[2], program);
                    ctx.emit("movzbl %al, %edx");
                    ctx.emit("shll $8, %edx");
                    ctx.emit("popl %eax");
                    ctx.emit("movzbl %al, %eax");
                    ctx.emit("orl %edx, %eax");
                    ctx.emit("popl %ecx");
                    ctx.emit("movw %ax, 0xB8000(,%ecx,2)");
                    ctx.emit("xorl %eax, %eax");
                    return;
                }
                "port_out8" if args.len() == 2 => {
                    emit_expr(ctx, &args[0], program);
                    ctx.emit("pushl %eax");
                    emit_expr(ctx, &args[1], program);
                    ctx.emit("popl %edx");
                    ctx.emit("outb %al, %dx");
                    ctx.emit("xorl %eax, %eax");
                    return;
                }
                "port_in8" if args.len() == 1 => {
                    emit_expr(ctx, &args[0], program);
                    ctx.emit("movl %eax, %edx");
                    ctx.emit("xorl %eax, %eax");
                    ctx.emit("inb %dx, %al");
                    return;
                }
                "mem_write8" if args.len() == 2 => {
                    emit_expr(ctx, &args[0], program);
                    ctx.emit("pushl %eax");
                    emit_expr(ctx, &args[1], program);
                    ctx.emit("popl %ecx");
                    ctx.emit("movb %al, (%ecx)");
                    ctx.emit("xorl %eax, %eax");
                    return;
                }
                "mem_read8" if args.len() == 1 => {
                    emit_expr(ctx, &args[0], program);
                    ctx.emit("movzbl (%eax), %eax");
                    return;
                }
                "cpu_cli" => {
                    ctx.emit("cli");
                    ctx.emit("xorl %eax, %eax");
                    return;
                }
                "cpu_sti" => {
                    ctx.emit("sti");
                    ctx.emit("xorl %eax, %eax");
                    return;
                }
                "cpu_halt" => {
                    ctx.emit("hlt");
                    ctx.emit("xorl %eax, %eax");
                    return;
                }
                _ => {}
            }
            let mut mut_flags = vec![false; args.len()];
            if let Some(fdef) = program.functions.iter().find(|f| f.name == *name) {
                for (i, p) in fdef.params.iter().enumerate() {
                    if i < mut_flags.len() {
                        mut_flags[i] = p.is_mut_ref;
                    }
                }
            }
            for (arg, is_mut) in args.iter().zip(mut_flags.iter()).rev() {
                if *is_mut {
                    if let Expr::Var(vname) = arg {
                        if ctx.ptr_params.contains(vname) {
                            let off = *ctx.locals.get(vname).unwrap_or(&8);
                            ctx.emit(&format!("movl {}(%ebp), %eax", off));
                        } else if let Some(&off) = ctx.locals.get(vname) {
                            ctx.emit(&format!("leal {}(%ebp), %eax", off));
                        } else {
                            emit_expr(ctx, arg, program);
                        }
                    } else {
                        emit_expr(ctx, arg, program);
                    }
                } else {
                    emit_expr(ctx, arg, program);
                }
                ctx.emit("pushl %eax");
            }
            ctx.emit(&format!("call {}", name));
            if !args.is_empty() {
                ctx.emit(&format!("addl ${}, %esp", args.len() * 4));
            }
        }
        Expr::BinOp(l, op, r) => {
            if let Expr::Number(imm) = r.as_ref() {
                emit_expr(ctx, l, program);
                match op.as_str() {
                    "+" => {
                        ctx.emit(&format!("addl ${}, %eax", imm));
                        return;
                    }
                    "-" => {
                        ctx.emit(&format!("subl ${}, %eax", imm));
                        return;
                    }
                    "&" => {
                        ctx.emit(&format!("andl ${}, %eax", imm));
                        return;
                    }
                    "|" => {
                        ctx.emit(&format!("orl ${}, %eax", imm));
                        return;
                    }
                    "^" => {
                        ctx.emit(&format!("xorl ${}, %eax", imm));
                        return;
                    }
                    "<<" => {
                        ctx.emit(&format!("sall ${}, %eax", imm));
                        return;
                    }
                    ">>" => {
                        ctx.emit(&format!("sarl ${}, %eax", imm));
                        return;
                    }
                    _ => {}
                }
            }

            if let Expr::Var(vname) = r.as_ref() {
                if !ctx.consts.contains_key(vname) {
                    if let Some(&off) = ctx.locals.get(vname) {
                        emit_expr(ctx, l, program);
                        match op.as_str() {
                            "+" => {
                                ctx.emit(&format!("addl {}(%ebp), %eax", off));
                                return;
                            }
                            "-" => {
                                ctx.emit(&format!("subl {}(%ebp), %eax", off));
                                return;
                            }
                            "&" => {
                                ctx.emit(&format!("andl {}(%ebp), %eax", off));
                                return;
                            }
                            "|" => {
                                ctx.emit(&format!("orl {}(%ebp), %eax", off));
                                return;
                            }
                            "^" => {
                                ctx.emit(&format!("xorl {}(%ebp), %eax", off));
                                return;
                            }
                            _ => {}
                        }
                    }
                }
            }
            emit_expr(ctx, l, program);
            ctx.emit("pushl %eax");
            emit_expr(ctx, r, program);
            ctx.emit("movl %eax, %ecx");
            ctx.emit("popl %eax");
            match op.as_str() {
                "+" => ctx.emit("addl %ecx, %eax"),
                "-" => ctx.emit("subl %ecx, %eax"),
                "*" => ctx.emit("imull %ecx, %eax"),
                "/" => {
                    ctx.emit("cdq");
                    ctx.emit("idivl %ecx");
                }
                "%" => {
                    ctx.emit("cdq");
                    ctx.emit("idivl %ecx");
                    ctx.emit("movl %edx, %eax");
                }
                "<<" => ctx.emit("sall %cl, %eax"),
                ">>" => ctx.emit("sarl %cl, %eax"),
                "&" => ctx.emit("andl %ecx, %eax"),
                "|" => ctx.emit("orl %ecx, %eax"),
                "^" => ctx.emit("xorl %ecx, %eax"),
                "==" | "!=" | "<" | "<=" | ">" | ">=" => {
                    let set_cc = match op.as_str() {
                        "==" => "sete",
                        "!=" => "setne",
                        "<" => "setl",
                        "<=" => "setle",
                        ">" => "setg",
                        ">=" => "setge",
                        _ => "sete",
                    };
                    ctx.emit("cmpl %ecx, %eax");
                    ctx.emit(&format!("{} %al", set_cc));
                    ctx.emit("movzbl %al, %eax");
                }
                "&&" => {
                    ctx.emit("cmpl $0, %eax");
                    ctx.emit("setne %al");
                    ctx.emit("cmpl $0, %ecx");
                    ctx.emit("setne %cl");
                    ctx.emit("andb %cl, %al");
                    ctx.emit("movzbl %al, %eax");
                }
                "||" => {
                    ctx.emit("orl %ecx, %eax");
                    ctx.emit("cmpl $0, %eax");
                    ctx.emit("setne %al");
                    ctx.emit("movzbl %al, %eax");
                }
                _ => {}
            }
        }
        Expr::StructInit(..) => ctx.emit("movl $0, %eax"),
    }
}

pub fn generate_x86_64_asm(program: &Program, is_kernel: bool) -> String {
    let mut out =
        String::from("# Generated by VETO Native x86_64 Backend (0 GCC dependency)\n.code64\n");
    if is_kernel {
        out.push_str(".bss\n.align 16\nkernel_stack64:\n.skip 32768\nkernel_stack64_top:\n.text\n.global _start\n_start:\n    cli\n    leaq kernel_stack64_top(%rip), %rsp\n    call main\n.L_halt64:\n    hlt\n    jmp .L_halt64\n\n");
    } else {
        out.push_str(".text\n");
    }
    let arg_regs = ["%rdi", "%rsi", "%rdx", "%rcx", "%r8", "%r9"];
    for func in &program.functions {
        out.push_str(&format!(
            ".global {}\n{}:\n    pushq %rbp\n    movq %rsp, %rbp\n",
            func.name, func.name
        ));
        for (i, _p) in func.params.iter().enumerate().take(6) {
            out.push_str(&format!("    # param {} in {}\n", i, arg_regs[i]));
        }
        for stmt in &func.body {
            match stmt {
                Stmt::InlineAsm { template, .. } => out.push_str(&format!("    {}\n", template)),
                Stmt::Return { expr, .. } => {
                    if let Expr::Number(n) = expr {
                        out.push_str(&format!("    movq ${}, %rax\n", n));
                    } else if let Expr::BinOp(l, op, r) = expr {
                        if let (Expr::Var(_), Expr::Var(_)) = (l.as_ref(), r.as_ref()) {
                            out.push_str("    movq %rdi, %rax\n");
                            if op == "+" {
                                out.push_str("    addq %rsi, %rax\n");
                            } else if op == "-" {
                                out.push_str("    subq %rsi, %rax\n");
                            }
                        }
                    } else if let Expr::Var(_) = expr {
                        out.push_str("    movq %rdi, %rax\n");
                    }
                    out.push_str("    popq %rbp\n    ret\n");
                }
                _ => {}
            }
        }
        out.push_str("    popq %rbp\n    ret\n\n");
    }
    out
}

pub fn generate_arm64_asm(program: &Program) -> String {
    let mut out =
        String::from("// Generated by VETO Native ARM64 (AArch64) Backend\n.text\n.align 2\n");
    for func in &program.functions {
        out.push_str(&format!(
            ".global {}\n{}:\n    stp x29, x30, [sp, #-16]!\n    mov x29, sp\n",
            func.name, func.name
        ));
        for stmt in &func.body {
            if let Stmt::Return { expr, .. } = stmt {
                if let Expr::Number(n) = expr {
                    out.push_str(&format!("    mov x0, #{}\n", n));
                } else if let Expr::BinOp(_, op, _) = expr {
                    if op == "+" {
                        out.push_str("    add x0, x0, x1\n");
                    } else if op == "-" {
                        out.push_str("    sub x0, x0, x1\n");
                    }
                }
                out.push_str("    ldp x29, x30, [sp], #16\n    ret\n");
            }
        }
        out.push_str("    ldp x29, x30, [sp], #16\n    ret\n\n");
    }
    out
}
